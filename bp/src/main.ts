world.afterEvents.worldLoad.subscribe(() => {
    initModules();
    if (get("worldBorder")) worldBorderOn();
    if (get("oreAlert")) oreAlertOn();
    if (get("endLock") || get("netherLock")) endNetherLockOn();
    if (get("antiGma") || get("antiGmc") || get("antiGms") || get("antiGmsp")) enableAntiGameMode();
    const movementModule = get("antiSpeedEnable") || get("antiFlyEnable");
    const killauraModule = get("antiKillauraEnable");
    if (movementModule || killauraModule) world.afterEvents.itemReleaseUse.subscribe(riptide);
    if (killauraModule || get("antiInvalidSprintEnable")) {
        world.afterEvents.itemStartUse.subscribe(itemStartUse);
        world.afterEvents.itemStopUse.subscribe(itemStopUse);
    }
    if (movementModule) {
        world.afterEvents.entityHurt.subscribe(knockback);
        world.beforeEvents.entityRemove.subscribe(entityRemove);
        world.afterEvents.entityDie.subscribe(entityDie);
    }
    if (world.getDynamicPropertyIds().find((id) => id.startsWith("banitem:"))) registerItemBanEvent();
    const allPlayers = world.getAllPlayers();
    if (allPlayers.length > 0) {
        try {
            allPlayers[0].runCommand("give @s element_0 1 1");
            allPlayers[0].runCommand("clear @s element_0 1 1");
            world.educationalFeaturesEnabled = true;
        } catch {
            world.educationalFeaturesEnabled = false;
        }
    }
});
world.beforeEvents.chatSend.subscribe((event) => {
    const player = event.sender;
    if (world.getDynamicProperty("automute") && !player?.chatEntered && !player.isOp()) {
        event.cancel = true;
        return;
    }
    const { x, y } = player.inputInfo.getMovementVector();
    if (x !== 0 || y !== 0) {
        event.cancel = true;
        player.sendMessage("§7[§aMatrix§7] §fPlease do not chat while you're moving!");
        return;
    }
    // Trash code for anti spam
    if (get("antiSpam") && !player.isOp()) {
        player.lastMessage ??= 0;
        player.tooFastFlag ??= 0;
        const now = Date.now();
        if (now - player.lastMessage <= get("antiSpamFastDef")) {
            player.tooFastFlag++;
            if (player.tooFastFlag > get("antiSpamTooFastFlagLimit")) {
                player.sendMessage("§7[§aMatrix§7] §fSlow down your message.");
                player.lastMessage = now;
                player.lastMessageRaw = event.message;
                event.cancel = true;
                return;
            }
        } else if (player.tooFastFlag > 0) player.tooFastFlag = 0;
        if (player.lastMessageRaw === event.message && now - player.lastMessage <= get("antiSpamRepeatDef")) {
            player.sendMessage("§7[§aMatrix§7] §fPlease don't spam message.");
            player.lastMessage = now;
            player.lastMessageRaw = event.message;
            event.cancel = true;
            return;
        }
        player.lastMessageRaw = event.message;
        if (longestContinuousChar(event.message) > get("antiSpamMaxRepeatedArgLength")) {
            player.sendMessage("§7[§aMatrix§7] §fPlease don't spam message!"); // ! means it is worser than . (idk)
            player.lastMessage = now;
            event.cancel = true;
            return;
        }
        player.lastMessage = now;
        if (event.message.length > get("antiSpamMessageMaxLength")) {
            player.sendMessage("§7[§aMatrix§7] §fYour message is too long.");
            event.cancel = true;
            return;
        }
    }
    if (get("chatRankEnable")) {
        const { message, sender: player } = event;
        const playerRank = getPlayerRank(player);
        const format = get("chatRankMessageFormat");
        world.sendMessage(format.replace("{rank}", playerRank).replace("{player}", player.name).replace("{message}", message));
        event.cancel = true;
        return;
    }
});
function longestContinuousChar(str: string) {
    // Remove all whitespace
    const cleaned = str.replaceAll(" ", "");

    if (cleaned.length === 0) return 0;

    let maxLen = 1;
    let currentLen = 1;

    for (let i = 1; i < cleaned.length; i++) {
        if (cleaned[i] === cleaned[i - 1]) {
            currentLen++;
            if (currentLen > maxLen) {
                maxLen = currentLen;
            }
        } else {
            currentLen = 1;
        }
    }

    return maxLen;
}
world.afterEvents.playerSpawn.subscribe(({ player, initialSpawn }) => {
    if (!initialSpawn) return;
    if (world?.lockdown && !player.isOp()) {
        player.kick("Server is locked down by operator, please try again later");
        return;
    }
    checkPunish(player);
    if (get("chatRankDisplayOnNameTag")) {
        const playerRank = getPlayerRank(player);
        const format = get("chatRankNameTagFormat");
        player.nameTag = format.replace("{rank}", playerRank).replace("{player}", player.name);
    }
    if (world.getDynamicProperty("automute") && !player.isOp()) {
        player.sendMessage("§7[§aAutoMute§7] §fUse §e/enterchat §fto unmute yourself.");
        player.runCommand("ability @s mute true");
    }
    if (world?.educationalFeaturesEnabled === undefined) {
        try {
            player.runCommand("give @s element_0 1");
            player.runCommand("clear @s element_0 0 1");
            world.educationalFeaturesEnabled = true;
        } catch {
            world.educationalFeaturesEnabled = false;
        }
    }
});
